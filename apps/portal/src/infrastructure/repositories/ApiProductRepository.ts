import { Brand, Product } from '../../domain/entities/Product';
import { ProductRepository, ProductFilter, CreateProductRequest } from '../../domain/repositories/ProductRepository';
import ApiClient, { API_V1, cleanParams, unwrap } from '../api/ApiClient';

const PRODUCTS_PATH = `${API_V1}/products`;
// max items per batch request (see docs/portal/flow/product/post-products-batch.md)
const BATCH_CHUNK_SIZE = 1000;

interface BrandResponse {
  uid: string;
  name_en: string;
  name_th: string;
}

interface ProductResponse {
  uid: string;
  merchant_uid: string;
  partner_id: string;
  name_en: string;
  name_th: string;
  sku: string;
  barcode: string;
  base_price: number;
  image_url: string;
  brand: BrandResponse | null;
  unit_name: string;
}

interface BatchProductError {
  index: number;
  name_en: string;
  message: string;
}

const toBrand = (b: BrandResponse): Brand => ({ uid: b.uid, nameEn: b.name_en, nameTh: b.name_th });

const toProduct = (p: ProductResponse): Product =>
  new Product(
    p.uid,
    p.merchant_uid,
    p.partner_id,
    p.name_en,
    p.name_th,
    p.sku,
    p.barcode,
    Number(p.base_price),
    p.image_url ?? '',
    p.brand ? toBrand(p.brand) : null,
    p.unit_name,
  );

const toProductBody = (r: CreateProductRequest) => ({
  uid: r.uid,
  merchant_uid: r.merchantId,
  name_en: r.nameEn,
  name_th: r.nameTh,
  barcode: r.barcode,
  base_price: r.basePrice,
  image_url: r.imageUrl || undefined,
  brand_uid: r.brandUid || undefined,
  unit_name: r.unitName || undefined,
});

export class ApiProductRepository implements ProductRepository {
  public async getProducts(page: number, limit: number, filters?: ProductFilter): Promise<{ products: Product[], total: number }> {
    const params = cleanParams({
      page,
      limit,
      barcode: filters?.barcode,
      name: filters?.name,
      merchant_uid: filters?.merchantId,
      brands: filters?.brands,
      units: filters?.units,
      price: filters?.price,
      store_uid: filters?.storeId,
    });
    const response = await ApiClient.get(PRODUCTS_PATH, { params });
    const { items, total } = unwrap<{ items: ProductResponse[]; total: number }>(response);

    return {
      products: items.map(toProduct),
      total
    };
  }

  public async getProductById(id: string): Promise<Product | null> {
    try {
      const response = await ApiClient.get(`${PRODUCTS_PATH}/${id}`);
      return toProduct(unwrap<ProductResponse>(response));
    } catch {
      return null;
    }
  }

  public async getFilterMetadata(): Promise<{ brands: Brand[], units: string[] }> {
    const response = await ApiClient.get(`${PRODUCTS_PATH}/metadata`);
    const { brands, units } = unwrap<{ brands: BrandResponse[]; units: string[] }>(response);
    return { brands: brands.map(toBrand), units };
  }

  public async createProduct(request: CreateProductRequest): Promise<Product> {
    // POST /api/v1/products does not accept `uid` (generated by the system)
    const body = { ...toProductBody(request), uid: undefined };
    const response = await ApiClient.post(PRODUCTS_PATH, body);
    return toProduct(unwrap<ProductResponse>(response));
  }

  public async createProducts(
    requests: CreateProductRequest[],
    onProgress?: (done: number, total: number) => void
  ): Promise<{ created: number; errors: string[] }> {
    let totalCreated = 0;
    const allErrors: string[] = [];

    for (let offset = 0; offset < requests.length; offset += BATCH_CHUNK_SIZE) {
      const chunk = requests.slice(offset, offset + BATCH_CHUNK_SIZE);
      const response = await ApiClient.post(`${PRODUCTS_PATH}/batch`, { products: chunk.map(toProductBody) });
      const { created, errors } = unwrap<{ created: number; errors?: BatchProductError[] }>(response);
      totalCreated += created;
      for (const e of errors ?? []) {
        // `index` is relative to the chunk; report the row number in the whole import (1-based)
        allErrors.push(`Row ${offset + e.index + 1} (${e.name_en}): ${e.message}`);
      }
      onProgress?.(Math.min(offset + BATCH_CHUNK_SIZE, requests.length), requests.length);
    }

    return { created: totalCreated, errors: allErrors };
  }
}
